'use strict';

// Node-RED loads one .html per node set. The editor of every node lives in its
// own file in editor/<type>.html (one node per file, each in its own IIFE);
// this script concatenates them into nodes/redkern-redis.html.
// Run: node scripts/build-editor.js [--check]

const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.join(__dirname, '..');
const ORDER = [
  'config', 'command', 'multi', 'scan', 'subscribe', 'list-in', 'stream-in', 'stream-out',
  'stream-ack', 'stream-claim', 'stream-gc', 'stream-metrics', 'stream-control'
];
const parts = ORDER.map((name) => {
  const file = path.join(ROOT, 'editor', `redkern-redis-${name}.html`);
  return `<!-- editor/redkern-redis-${name}.html -->\n${fs.readFileSync(file, 'utf8').trim()}\n`;
});
const extra = fs.readdirSync(path.join(ROOT, 'editor')).filter((file) => !ORDER.some((name) => file === `redkern-redis-${name}.html`));
if (extra.length) {
  console.error(`editor files not in ORDER: ${extra.join(', ')}`);
  process.exit(1);
}
const content = `<!-- Generated by scripts/build-editor.js from editor/*.html. Do not edit. -->\n${parts.join('\n')}`;
const target = path.join(ROOT, 'nodes', 'redkern-redis.html');
if (process.argv.includes('--check')) {
  if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== content) {
    console.error('stale nodes/redkern-redis.html: run node scripts/build-editor.js');
    process.exit(1);
  }
} else {
  fs.writeFileSync(target, content);
}
